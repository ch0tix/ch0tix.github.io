/* =========================================================================
   Full-screen interactive console  —  ch0tix.github.io
   Entered via the /console menu item; it SUBSTITUTES the whole site.
   The site is a filesystem: each page is a folder (me/, blog/), each post a
   file. Navigate with ls / cd / open / cat. Leave with `exit` (or `gui`, Esc).
   Data comes from /index.json, generated by Hugo from your content + config.
   ========================================================================= */
(function () {
  "use strict";

  var script   = document.currentScript;
  var DATA_URL = (script && script.getAttribute("data-base")) || "/index.json";

  var overlay, output, input, promptEl;
  var DATA = null;
  var booted = false;
  var history = [];
  var histIdx = -1;
  var PROMPT = "ch0tix@web:~$";

  var BANNER = [
    " ██████╗██╗  ██╗ ██████╗ ████████╗██╗██╗  ██╗",
    "██╔════╝██║  ██║██╔═████╗╚══██╔══╝██║╚██╗██╔╝",
    "██║     ███████║██║██╔██║   ██║   ██║ ╚███╔╝ ",
    "██║     ██╔══██║████╔╝██║   ██║   ██║ ██╔██╗ ",
    "╚██████╗██║  ██║╚██████╔╝   ██║   ██║██╔╝ ██╗",
    " ╚═════╝╚═╝  ╚═╝ ╚═════╝    ╚═╝   ╚═╝╚═╝  ╚═╝"
  ].join("\n");

  // ---- helpers ------------------------------------------------------------
  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;")
      .replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }
  function write(html) {
    var div = document.createElement("div");
    div.className = "c-row";
    div.innerHTML = html;
    output.appendChild(div);
    output.scrollTop = output.scrollHeight;
  }
  function blank() { write("&nbsp;"); }

  function posts()    { return (DATA && DATA.posts) || []; }
  function blogUrl()  { return (DATA && DATA.site && DATA.site.postsUrl) || "/blog/"; }
  function meUrl()    {
    var pages = (DATA && DATA.pages) || [];
    for (var i = 0; i < pages.length; i++) {
      if (/\/me\/?$/.test(pages[i].url) || pages[i].title.toLowerCase() === "me") return pages[i].url;
    }
    return "/me/";
  }

  // folders of the "filesystem": name -> url
  function folders() {
    return [
      { name: "me",   url: meUrl(),   desc: "about me" },
      { name: "blog", url: blogUrl(), desc: "posts" }
    ];
  }

  function findPost(ref) {
    var ps = posts();
    if (ref == null || ref === "") return null;
    var n = parseInt(ref, 10);
    if (!isNaN(n) && String(n) === String(ref).trim()) return ps[n - 1] || null;
    ref = String(ref).toLowerCase();
    for (var i = 0; i < ps.length; i++) {
      if (ps[i].url.toLowerCase().indexOf(ref) !== -1 ||
          ps[i].title.toLowerCase().indexOf(ref) !== -1) return ps[i];
    }
    return null;
  }

  // Resolve a path argument to an action. Returns {type, url?, post?}.
  function resolve(arg) {
    if (arg == null) arg = "";
    var a = String(arg).trim().toLowerCase().replace(/\/+$/, "");
    if (a === "" || a === "~" || a === "/" || a === ".." || a === ".")
      return { type: "home" };
    var fs = folders();
    for (var i = 0; i < fs.length; i++) if (fs[i].name === a) return { type: "folder", url: fs[i].url, name: fs[i].name };
    var p = findPost(arg);
    if (p) return { type: "post", post: p };
    return { type: "none" };
  }

  function go(url) { setMode("graphic"); window.location.href = url; }

  // ---- commands -----------------------------------------------------------
  var COMMANDS = {
    help: {
      help: "show this help",
      run: function () {
        write('<span class="c-accent">this site is a filesystem — every page is a folder.</span>');
        var order = ["ls", "cd", "open", "cat", "me", "blog", "posts",
          "whoami", "skills", "projects", "social", "clear", "banner",
          "echo", "date", "uname", "pwd", "history", "exit"];
        var rows = '<div class="c-table">';
        order.forEach(function (name) {
          var c = COMMANDS[name];
          if (!c) return;
          rows += '<span class="c-cmd">' + esc(name) + "</span><span>" + esc(c.help) + "</span>";
        });
        rows += "</div>";
        write(rows);
        write('<span class="c-dim">↑/↓ history · Tab complete · Esc / `exit` return to the site.</span>');
      }
    },

    ls: {
      help: "list folders & files",
      run: function () {
        folders().forEach(function (f) {
          write('<a href="' + esc(f.url) + '" class="c-accent">' + esc(f.name) +
            '/</a>  <span class="c-dim">' + esc(f.desc) + "</span>");
        });
        var ps = posts();
        if (ps.length) {
          write('<span class="c-dim">blog/</span>');
          ps.forEach(function (p, i) {
            write('  <span class="c-dim">' + String(i + 1).padStart(2, "0") + "</span>  " +
              '<a href="' + esc(p.url) + '">' + esc(p.title) + "</a>");
          });
        }
        write('<span class="c-dim">→ enter a folder: </span><span class="c-cmd">cd me</span>' +
          '<span class="c-dim">  ·  open a post: </span><span class="c-cmd">open 1</span>');
      }
    },

    cd: {
      help: "enter a folder:  cd me | cd blog | cd <post> | cd /",
      run: function (args) {
        var r = resolve(args[0]);
        if (r.type === "home") { write('<span class="c-dim">returning to the site…</span>'); return COMMANDS.exit.run(); }
        if (r.type === "folder") { write('<span class="c-dim">opening ' + esc(r.url) + " …</span>"); return go(r.url); }
        if (r.type === "post")   { write('<span class="c-dim">opening ' + esc(r.post.url) + " …</span>"); return go(r.post.url); }
        write('<span class="c-error">cd: no such folder: ' + esc(args[0] || "") + "</span>");
      }
    },

    open: {
      help: "open a page/post in the browser:  open <name|n>",
      run: function (args) { return COMMANDS.cd.run(args); }
    },

    cat: {
      help: "read without leaving the console:  cat me | cat <post>",
      run: function (args) {
        var a = String(args[0] || "").trim().toLowerCase();
        if (a === "me" || a === "about") {
          var lines = (DATA && DATA.about) || ["(empty — edit hugo.toml → params.consoleAbout)"];
          lines.forEach(function (l) { write(l === "" ? "&nbsp;" : esc(l)); });
          write('<span class="c-dim">→ full page: </span><span class="c-cmd">open me</span>');
          return;
        }
        if (a === "blog") return COMMANDS.posts.run();
        var p = findPost(args[0]);
        if (!p) return write('<span class="c-error">cat: no such file: ' + esc(args[0] || "") + "</span>");
        write('<span class="c-cmd">' + esc(p.title) + '</span> <span class="c-dim">(' + esc(p.date) + ")</span>");
        if (p.summary) write(esc(p.summary));
        write('<span class="c-dim">→ read it: </span><span class="c-cmd">open ' + esc(args[0]) + "</span>");
      }
    },

    me:   { help: "go to the /me page",   run: function () { return COMMANDS.cd.run(["me"]); } },
    blog: { help: "go to the /blog page", run: function () { return COMMANDS.cd.run(["blog"]); } },

    posts: {
      help: "list blog posts",
      run: function () {
        var ps = posts();
        if (!ps.length) return write('<span class="c-dim">(no posts yet)</span>');
        ps.forEach(function (p, i) {
          write('<span class="c-dim">' + String(i + 1).padStart(2, "0") + "</span>  " +
            '<span class="c-dim">' + esc(p.date) + "</span>  " +
            '<a href="' + esc(p.url) + '">' + esc(p.title) + "</a>");
        });
        write('<span class="c-dim">→ </span><span class="c-cmd">open &lt;n&gt;</span>' +
          '<span class="c-dim"> or </span><span class="c-cmd">cat &lt;n&gt;</span>');
      }
    },

    whoami: {
      help: "print identity",
      run: function () {
        var name = (DATA && DATA.site && DATA.site.author) || "ch0tix";
        var sub = (DATA && DATA.site && DATA.site.subtitle) || "";
        write('<span class="c-accent">' + esc(name) + "</span>");
        if (sub) write('<span class="c-dim">' + esc(sub) + "</span>");
        write('<span class="c-dim">→ more: </span><span class="c-cmd">cat me</span>');
      }
    },

    skills: {
      help: "list skills / toolbox",
      run: function () {
        var s = (DATA && DATA.skills) || [];
        if (!s.length) return write('<span class="c-dim">(no skills configured)</span>');
        s.forEach(function (l) { write(esc(l)); });
      }
    },

    projects: {
      help: "list projects",
      run: function () {
        var p = (DATA && DATA.projects) || [];
        if (!p.length) return write('<span class="c-dim">(no projects configured)</span>');
        p.forEach(function (pr) {
          var head = '<span class="c-cmd">' + esc(pr.name) + "</span>";
          if (pr.url) head += '  <a href="' + esc(pr.url) + '" target="_blank" rel="noopener">' + esc(pr.url) + "</a>";
          write(head);
          if (pr.desc) write('<span class="c-dim">  ' + esc(pr.desc) + "</span>");
        });
      }
    },

    social: {
      help: "contact / social links",
      run: function () {
        var s = (DATA && DATA.social) || {};
        var any = false;
        Object.keys(s).forEach(function (k) {
          if (!s[k]) return;
          any = true;
          var href = (k === "email") ? "mailto:" + s[k] : s[k];
          write('<span class="c-cmd">' + esc(k) + "</span>  :: " +
            '<a href="' + esc(href) + '" target="_blank" rel="noopener">' + esc(s[k]) + "</a>");
        });
        if (!any) write('<span class="c-dim">(no social links configured)</span>');
      }
    },
    contact: { help: "alias of social", run: function () { COMMANDS.social.run(); } },

    clear:  { help: "clear the screen", run: function () { output.innerHTML = ""; } },
    cls:    { help: "alias of clear", run: function () { output.innerHTML = ""; } },
    banner: { help: "print the banner", run: printBanner },
    echo:   { help: "echo text", run: function (args, raw) { write(esc(raw.slice(4).trim())); } },
    date:   { help: "print the date", run: function () { write(esc(new Date().toString())); } },
    uname:  { help: "system info", run: function () { write("ch0tix-web 6.x #1 SMP x86_64 GNU/Linux"); } },
    pwd:    { help: "working directory", run: function () { write("/home/ch0tix"); } },
    history: {
      help: "command history",
      run: function () { history.forEach(function (h, i) { write('<span class="c-dim">' + (i + 1) + "</span>  " + esc(h)); }); }
    },
    sudo: { help: null, run: function () { write('<span class="c-error">ch0tix is not in the sudoers file. This incident will be reported.</span>'); } },

    exit: { help: "return to the graphic site", run: closeConsole },
    gui:  { help: null, run: closeConsole },
    q:    { help: null, run: closeConsole }
  };

  function printBanner() { write('<span class="c-banner">' + esc(BANNER) + "</span>"); }

  function boot() {
    if (booted) return;
    booted = true;
    printBanner();
    var sub = (DATA && DATA.site && DATA.site.subtitle) || "security researcher & engineer";
    write('<span class="c-dim">' + esc(sub) + "</span>");
    blank();
    write('This site is a filesystem. <span class="c-cmd">ls</span> to look around, ' +
      '<span class="c-cmd">help</span> for commands, <span class="c-cmd">exit</span> to return to the site.');
    blank();
  }

  // ---- execution ----------------------------------------------------------
  function run(raw) {
    var line = raw.trim();
    write('<span class="c-prompt">' + esc(PROMPT) + '</span> <span class="c-echo">' + esc(line) + "</span>");
    if (!line) return;
    history.push(line); histIdx = history.length;
    var parts = line.split(/\s+/);
    var name = parts[0].toLowerCase();
    var args = parts.slice(1);
    var cmd = COMMANDS[name];
    if (cmd) {
      try { cmd.run(args, line); }
      catch (e) { write('<span class="c-error">error: ' + esc(e.message) + "</span>"); }
    } else {
      write('<span class="c-error">' + esc(name) + ": command not found</span>");
      write('<span class="c-dim">type </span><span class="c-cmd">help</span><span class="c-dim"> for a list.</span>');
    }
    blank();
  }

  // ---- mode switching -----------------------------------------------------
  function setMode(mode) { try { localStorage.setItem("site-mode", mode); } catch (e) {} }

  function openConsole() {
    document.documentElement.classList.add("console-active");
    if (overlay) overlay.setAttribute("aria-hidden", "false");
    setMode("console");
    boot();
    setTimeout(function () { if (input) input.focus(); }, 30);
  }

  function closeConsole() {
    document.documentElement.classList.remove("console-active");
    if (overlay) overlay.setAttribute("aria-hidden", "true");
    setMode("graphic");
    // drop the #console hash if we arrived through it
    if (window.location.hash === "#console") {
      try { window.history.replaceState(null, "", window.location.pathname + window.location.search); }
      catch (e) { window.location.hash = ""; }
    }
    try { window.scrollTo(0, 0); } catch (e) {}
  }

  // ---- input --------------------------------------------------------------
  function onKey(e) {
    if (e.key === "Enter") {
      var v = input.value; input.value = ""; run(v);
    } else if (e.key === "ArrowUp") {
      if (histIdx > 0) { histIdx--; input.value = history[histIdx] || ""; }
      e.preventDefault();
    } else if (e.key === "ArrowDown") {
      if (histIdx < history.length) { histIdx++; input.value = history[histIdx] || ""; }
      e.preventDefault();
    } else if (e.key === "Tab") {
      e.preventDefault();
      var frag = input.value.trim().toLowerCase();
      if (!frag) return;
      var matches = Object.keys(COMMANDS).filter(function (c) {
        return COMMANDS[c].help !== null && c.indexOf(frag) === 0;
      });
      if (matches.length === 1) input.value = matches[0] + " ";
      else if (matches.length > 1) write('<span class="c-dim">' + matches.join("  ") + "</span>");
    } else if (e.key === "Escape") {
      closeConsole();
    } else if (e.key === "l" && e.ctrlKey) {
      e.preventDefault(); output.innerHTML = "";
    }
  }

  // ---- wiring -------------------------------------------------------------
  function init() {
    overlay  = document.getElementById("console-overlay");
    output   = document.getElementById("console-output");
    input    = document.getElementById("console-input");
    promptEl = document.getElementById("console-prompt");
    if (!overlay || !output || !input) return;

    promptEl.textContent = PROMPT;
    input.addEventListener("keydown", onKey);

    overlay.addEventListener("mousedown", function (e) {
      if (e.target === overlay || e.target.id === "console-window") { e.preventDefault(); input.focus(); }
    });

    // any link/button pointing at #console opens the console
    document.addEventListener("click", function (e) {
      var a = e.target.closest('a[href$="#console"], a[href="#console"], [data-console]');
      if (a) { e.preventDefault(); openConsole(); }
    });

    fetch(DATA_URL, { cache: "no-cache" })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (json) { DATA = json; })
      .catch(function () { DATA = null; })
      .finally(function () {
        if (document.documentElement.classList.contains("console-active")) openConsole();
      });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
